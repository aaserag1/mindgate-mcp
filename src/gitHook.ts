/**
 * MindGate Git Post-Commit Hook Adapter (v1.3.0)
 *
 * Automatically captures git commit messages, authors, and touched files
 * into MindGate sessions, maintaining unbroken project context even when
 * the developer works outside an AI agent.
 */

import childProcess from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { MindGateStore } from "./db/memoryStore.js";

const HOOK_START_MARKER = "# --- mindgate:post-commit:start ---";
const HOOK_END_MARKER = "# --- mindgate:post-commit:end ---";

export function findGitRoot(startDir: string = process.cwd()): string | null {
  let curr = path.resolve(startDir);
  while (true) {
    const gitDir = path.join(curr, ".git");
    if (fs.existsSync(gitDir)) {
      return curr;
    }
    const parent = path.dirname(curr);
    if (parent === curr) break;
    curr = parent;
  }
  return null;
}

export function installGitHook(targetDir?: string, binPath?: string): {
  success: boolean;
  hookPath: string;
  message: string;
} {
  const root = findGitRoot(targetDir || process.cwd());
  if (!root) {
    return {
      success: false,
      hookPath: "",
      message: "Not inside a Git repository (.git not found).",
    };
  }

  const hooksDir = path.join(root, ".git", "hooks");
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const hookFile = path.join(hooksDir, "post-commit");
  const scriptLocation = binPath
    ? path.resolve(binPath).replace(/\\/g, "/")
    : "mindgate-mcp";

  const hookBlock = `${HOOK_START_MARKER}
# Auto-generated by MindGate (بوابة العقل) — Cross-agent git context capture
if command -v node >/dev/null 2>&1; then
  node "${scriptLocation}" capture-commit "$PWD" >/dev/null 2>&1 &
elif command -v mindgate-mcp >/dev/null 2>&1; then
  mindgate-mcp capture-commit "$PWD" >/dev/null 2>&1 &
fi
${HOOK_END_MARKER}`;

  let existing = "";
  if (fs.existsSync(hookFile)) {
    existing = fs.readFileSync(hookFile, "utf8");
    if (existing.includes(HOOK_START_MARKER)) {
      return {
        success: true,
        hookPath: hookFile,
        message: "MindGate post-commit hook is already installed.",
      };
    }
  }

  const shebang = "#!/bin/sh";
  let finalContent: string;
  if (!existing || existing.trim().length === 0) {
    finalContent = `${shebang}\n${hookBlock}\n`;
  } else if (!existing.startsWith("#!")) {
    finalContent = `${shebang}\n${existing}\n\n${hookBlock}\n`;
  } else {
    finalContent = `${existing.trimEnd()}\n\n${hookBlock}\n`;
  }

  fs.writeFileSync(hookFile, finalContent, { encoding: "utf8", mode: 0o755 });

  try {
    fs.chmodSync(hookFile, 0o755);
  } catch {
    // Windows chmod is a no-op
  }

  return {
    success: true,
    hookPath: hookFile,
    message: `MindGate post-commit hook successfully installed at: ${hookFile}`,
  };
}

export function uninstallGitHook(targetDir?: string): {
  success: boolean;
  hookPath: string;
  message: string;
} {
  const root = findGitRoot(targetDir || process.cwd());
  if (!root) {
    return {
      success: false,
      hookPath: "",
      message: "Not inside a Git repository (.git not found).",
    };
  }

  const hookFile = path.join(root, ".git", "hooks", "post-commit");
  if (!fs.existsSync(hookFile)) {
    return {
      success: false,
      hookPath: hookFile,
      message: "No post-commit hook found.",
    };
  }

  const content = fs.readFileSync(hookFile, "utf8");
  if (!content.includes(HOOK_START_MARKER)) {
    return {
      success: false,
      hookPath: hookFile,
      message:
        "Existing post-commit hook was not generated by MindGate; refusing to remove.",
    };
  }

  // Remove the MindGate block between start and end markers
  const startIdx = content.indexOf(HOOK_START_MARKER);
  const endIdx = content.indexOf(HOOK_END_MARKER);
  let remaining: string;
  if (startIdx !== -1 && endIdx !== -1) {
    const before = content.substring(0, startIdx);
    const after = content.substring(endIdx + HOOK_END_MARKER.length);
    remaining = (before + after).trim();
  } else {
    remaining = "";
  }

  if (remaining.length === 0 || remaining === "#!/bin/sh") {
    try {
      fs.unlinkSync(hookFile);
    } catch {
      // ignore
    }
  } else {
    fs.writeFileSync(hookFile, remaining + "\n", "utf8");
  }

  return {
    success: true,
    hookPath: hookFile,
    message: "MindGate post-commit hook removed successfully.",
  };
}

export function captureCommitHandoff(repoDir?: string, store?: MindGateStore): {
  logged: boolean;
  commitHash?: string;
  summary?: string;
  message: string;
} {
  const root = findGitRoot(repoDir || process.cwd());
  if (!root) {
    return { logged: false, message: "Directory is not a git repository." };
  }

  try {
    const gitLog = childProcess
      .execSync('git log -1 --pretty=format:"%H%n%an%n%s"', {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      })
      .trim();

    const [commitHash, author, ...subjectParts] = gitLog.split("\n");
    const commitMessage = subjectParts.join("\n").trim() || "Git commit";

    let activeFiles: string[] = [];
    try {
      const diffTree = childProcess
        .execSync("git diff-tree --no-commit-id --name-only -r HEAD", {
          cwd: root,
          encoding: "utf8",
          stdio: ["ignore", "pipe", "ignore"],
        })
        .trim();
      activeFiles = diffTree.split("\n").map((f) => f.trim()).filter(Boolean);
    } catch {
      // Diff tree failed; proceed without file list
    }

    const workspace = path.basename(root);
    const activeStore = store || new MindGateStore();
    const shortHash = commitHash ? commitHash.substring(0, 8) : "head";

    const { record } = activeStore.logSessionSummary({
      workspace,
      sourceAgent: "git-hook",
      summary: `[Git Commit ${shortHash}] by ${author || "developer"}: ${commitMessage}`,
      activeFiles,
    });

    return {
      logged: true,
      commitHash,
      summary: record.summary,
      message: `Captured git commit #${record.id} for workspace "${workspace}".`,
    };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    return { logged: false, message: `Git execution error: ${msg}` };
  }
}
