/**
 * MindGate Rules Writer (v1.2.0)
 *
 * Safely writes generated workspace-rules files (AGENTS.md / CLAUDE.md /
 * .cursorrules / ...) to a project directory:
 *
 *  1. Atomic write: content goes to a temp file in the same directory and is
 *     then rename(2)d into place, so a crash never leaves a truncated file.
 *  2. Overwrite protection: an existing file that does NOT carry the MindGate
 *     sentinel marker is considered hand-written and is refused unless the
 *     caller passes `force: true`.
 *  3. Backup: before overwriting any existing file, a timestamped
 *     `<file>.bak-<timestamp>` copy is created next to it.
 */

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

/** Embedded in every MindGate-generated file so we can recognize our own output. */
export const RULES_SENTINEL = "<!-- mindgate:auto-generated -->";

export class RulesWriteError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "RulesWriteError";
  }
}

export interface WriteRulesResult {
  writtenTo: string;
  backupPath: string | null;
}

export function writeRulesFile(params: {
  projectDir: string;
  targetFile: string;
  markdown: string;
  force?: boolean;
}): WriteRulesResult {
  const { projectDir, targetFile, markdown, force = false } = params;

  const resolvedDir = path.resolve(projectDir);
  let stat: fs.Stats;
  try {
    stat = fs.statSync(resolvedDir);
  } catch {
    throw new RulesWriteError(
      `project_dir does not exist: ${resolvedDir}`
    );
  }
  if (!stat.isDirectory()) {
    throw new RulesWriteError(
      `project_dir is not a directory: ${resolvedDir}`
    );
  }

  const fullTarget = path.join(resolvedDir, targetFile);

  let backupPath: string | null = null;
  if (fs.existsSync(fullTarget)) {
    const existing = fs.readFileSync(fullTarget, "utf8");
    const isMindGateGenerated = existing.includes(RULES_SENTINEL);
    if (!isMindGateGenerated && !force) {
      throw new RulesWriteError(
        `Refusing to overwrite ${fullTarget}: the file exists and was not generated by MindGate ` +
          `(no ${RULES_SENTINEL} marker). Re-run with force=true to overwrite it (a .bak backup will be created).`
      );
    }
    backupPath = `${fullTarget}.bak-${Date.now()}`;
    fs.copyFileSync(fullTarget, backupPath);
  }

  // Atomic publish: write to a unique temp file in the same directory, then rename.
  const tmpPath = path.join(
    resolvedDir,
    `.${targetFile}.mindgate-${process.pid}-${crypto.randomBytes(6).toString("hex")}.tmp`
  );
  try {
    fs.writeFileSync(tmpPath, markdown, { encoding: "utf8", mode: 0o644 });
    fs.renameSync(tmpPath, fullTarget);
  } catch (err) {
    try {
      if (fs.existsSync(tmpPath)) fs.unlinkSync(tmpPath);
    } catch {
      // best-effort cleanup; nothing else to do
    }
    throw err;
  }

  return { writtenTo: fullTarget, backupPath };
}
